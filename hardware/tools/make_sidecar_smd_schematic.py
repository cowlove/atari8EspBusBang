#!/usr/bin/env python3
"""Generate the sidecar_smd schematic: the Sidecar carrier with bare modules.

Speculative. Starts from the espBusBangSidecar schematic (itself generated by
make_sidecar_schematic.py) and its netlist, and replaces both DevKitC symbols
with ESP32-S3-WROOM-1-N8R2 modules, keeping every GPIO's net. What the DevKitC
boards carried is added per module: an AMS1117-3.3 regulator from the
carrier's 5 V with its capacitors, decoupling, the EN RC reset and an IO0
pull-up. Each module gets a 6-pin debug/flash header (J4 Sidecar, J5 main),
and jumper J6 separates the board's 5 V rail from the Atari's.

    kicad-cli sch export netlist -o /tmp/sc.net hardware/espBusBangSidecar/espBusBangSidecar.kicad_sch
    python3 hardware/tools/make_sidecar_smd_schematic.py \\
        hardware/espBusBangSidecar/espBusBangSidecar.kicad_sch /tmp/sc.net \\
        <kicad>/share/kicad/symbols hardware/sidecar_smd/sidecar_smd.kicad_sch

The symbols directory is KiCad's standard library (for RF_Module,
Regulator_Linear and Device). Deterministic UUIDs: reruns only show changes.
"""
import re
import sys
import uuid

src_sch, src_net, symdir, dst = sys.argv[1:5]
s = open(src_sch).read()
net_text = open(src_net).read()

_n = 0


def U():
    global _n
    _n += 1
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"atari8EspBusBang/sidecar_smd/{_n}"))


def block(text, start):
    d = 0
    for j in range(start, len(text)):
        if text[j] == '(':
            d += 1
        elif text[j] == ')':
            d -= 1
            if d == 0:
                return text[start:j + 1]
    raise ValueError("unbalanced")


ROOT = re.search(r'\(uuid "([^"]+)"\)', s).group(1)

# --- Nets of U1 and U2 by GPIO, from the DevKitC version's netlist.
gpio_net = {"U1": {}, "U2": {}}
power_net = {"U1": {}, "U2": {}}
for name, body in re.findall(r'\(net \(code "\d+"\) \(name "([^"]+)"\)(.*?)\)\s*(?=\(net |\)\s*\)\s*$)',
                             net_text, re.S):
    if name.startswith("unconnected-"):
        continue
    for ref, pin, pinfn in re.findall(r'\(node \(ref "(U[12])"\) \(pin "([^"]+)"\) \(pinfunction "([^"]*)"',
                                      body):
        m = re.match(r'GPIO(\d+)', pinfn)
        if m:
            gpio_net[ref][int(m.group(1))] = name.lstrip('/')
        elif pinfn in ("3V3", "5V", "GND", "CHIP_PU"):
            power_net[ref][pinfn] = name.lstrip('/')
assert gpio_net["U1"] and gpio_net["U2"], "no U1/U2 nets in the netlist"

# --- Drop U1, U2 and the labels on their pins, and the DevKitC symbol.
devkit = block(s, s.index('(symbol "Espressif:ESP32-S3-DevKitC"'))
dk_pins = [(float(x), float(y)) for x, y in
           re.findall(r'\(pin \w+ \w+\s*\(at ([-\d.]+) ([-\d.]+) \d+\)', devkit)]
centers = {}
for ref in ("U1", "U2"):
    m = re.search(r'\n\t\(symbol\n\t\t\(lib_id "Espressif:ESP32-S3-DevKitC"\)\n\t\t\(at ([-\d.]+) ([-\d.]+) 0\)'
                  r'(?:(?!\n\t\(symbol\n).)*?\(reference "' + ref + r'"\)', s, re.S)
    assert m, ref
    centers[ref] = (float(m.group(1)), float(m.group(2)))
    start = m.start() + 1
    s = s[:start] + s[start + len(block(s, start)):]
spots = {(round(cx + px, 2), round(cy - py, 2)) for cx, cy in centers.values() for px, py in dk_pins}


def drop_label(m):
    x, y = round(float(m.group(2)), 2), round(float(m.group(3)), 2)
    return "" if (x, y) in spots else m.group(0)


s = re.sub(r'\t\(label "([^"]*)"\n\t\t\(at ([-\d.]+) ([-\d.]+) \d+\)\n(?:\t\t[^\n]*\n)*?\t\)\n', drop_label, s)
lib_start = s.index('(symbol "Espressif:ESP32-S3-DevKitC"')
lib_start = s.rindex('\n', 0, lib_start) + 1
paren = s.index('(symbol', lib_start)
s = s[:lib_start] + s[paren + len(block(s, paren)) + 1:]

# --- Drop J2, the microSD breakout header, and the labels on its pins: a
# real socket replaces it below.
m = re.search(r'\n\t\(symbol\n\t\t\(lib_id "Connector_Generic:Conn_01x08"\)\n\t\t\(at ([-\d.]+) ([-\d.]+) 0\)', s)
j2x, j2y = float(m.group(1)), float(m.group(2))
start = m.start() + 1
s = s[:start] + s[start + len(block(s, start)):]
spots = {(round(j2x - 5.08, 2), round(j2y - 7.62 + 2.54 * i, 2)) for i in range(8)}
s = re.sub(r'\t\(label "([^"]*)"\n\t\t\(at ([-\d.]+) ([-\d.]+) \d+\)\n(?:\t\t[^\n]*\n)*?\t\)\n', drop_label, s)

# --- Library symbols from KiCad's library, renamed lib:name for embedding.


def lib_symbol(libfile, name, as_name=None, override=None):
    t = open(f"{symdir}/{libfile}.kicad_sym").read()
    b = block(t, t.index(f'(symbol "{name}"'))
    ext = re.search(r'\(extends "([^"]+)"\)', b)
    if ext:
        # A derived symbol: the parent's body with the child's properties.
        parent = block(t, t.index(f'(symbol "{ext.group(1)}"'))
        for prop, val in re.findall(r'\(property "([^"]+)" "([^"]*)"', b):
            parent = re.sub(r'(\(property "' + re.escape(prop) + r'" ")[^"]*"',
                            lambda m: m.group(1) + val.replace('\\', '\\\\') + '"', parent, count=1)
        b = parent.replace(f'(symbol "{ext.group(1)}_', f'(symbol "{name}_')
        b = b.replace(f'(symbol "{ext.group(1)}"', f'(symbol "{name}"', 1)
    b = b.replace(f'(symbol "{name}"', f'(symbol "{libfile}:{name}"', 1)
    return "\t\t" + b.replace("\n", "\n\t") + "\n"


def pins_of(libfile, name):
    t = open(f"{symdir}/{libfile}.kicad_sym").read()
    b = block(t, t.index(f'(symbol "{name}"'))
    ext = re.search(r'\(extends "([^"]+)"\)', b)
    if ext:
        b = block(t, t.index(f'(symbol "{ext.group(1)}"'))
    return {num: (float(x), float(y), int(a), nm) for x, y, a, nm, num in
            re.findall(r'\(pin \w+ \w+\s*\(at ([-\d.]+) ([-\d.]+) (\d+)\)\s*\(length [\d.]+\)'
                       r'(?:\s*\(hide yes\))?.*?\(name "([^"]*)".*?\(number "([^"]*)"', b, re.S)}


new_libs = (lib_symbol("RF_Module", "ESP32-S3-WROOM-1")
            + lib_symbol("Regulator_Linear", "AMS1117-3.3")
            + lib_symbol("Device", "C")
            + lib_symbol("LED", "SK6812MINI")
            + lib_symbol("Connector", "Micro_SD_Card_Det_Hirose_DM3AT"))
wroom = pins_of("RF_Module", "ESP32-S3-WROOM-1")
ldo = pins_of("Regulator_Linear", "AMS1117-3.3")
cap = pins_of("Device", "C")
rgb = pins_of("LED", "SK6812MINI")
sdsock = pins_of("Connector", "Micro_SD_Card_Det_Hirose_DM3AT")
res = {"1": (0, 3.81, 270, "~"), "2": (0, -3.81, 90, "~")}

# A 1x06 header: the Conn_01x<n> template of make_sidecar_schematic.py.
_other = open(__file__.replace("make_sidecar_smd_schematic.py", "make_sidecar_schematic.py")).read()
_ns = {}
exec(_other[_other.index("CONN = "):_other.index("def conn_symbol")], _ns)   # CONN, CPIN
exec(_other[_other.index("def conn_symbol"):_other.index("lib_end = ")], _ns)
new_libs += _ns["conn_symbol"](6) + _ns["conn_symbol"](2)
close_idx = s.index('\t(lib_symbols')
close_idx = close_idx + 1 + len(block(s, close_idx + 1)) - 1
s = s[:close_idx].rstrip('\t') + new_libs + "\t" + s[close_idx:]

LABEL = '''\t(label "{name}"
\t\t(at {x:g} {y:g} {a})
\t\t(effects
\t\t\t(font
\t\t\t\t(size 1.27 1.27)
\t\t\t)
\t\t\t(justify {j} bottom)
\t\t)
\t\t(uuid "{u}")
\t)
'''


def label(name, x, y, a):
    return LABEL.format(name=name, x=round(x, 4), y=round(y, 4), a=a,
                        j="left" if a in (0, 90) else "right", u=U())


def prop(name, value, x, y, hide=False):
    h = "\n\t\t\t\t(hide yes)" if hide else ""
    return (f'\t\t(property "{name}" "{value}"\n\t\t\t(at {x:g} {y:g} 0)\n\t\t\t(effects\n'
            f'\t\t\t\t(font\n\t\t\t\t\t(size 1.27 1.27)\n\t\t\t\t){h}\n\t\t\t)\n\t\t)\n')


out = []


def place(lib_id, ref, value, footprint, x, y, pinmap, nets):
    """Place a symbol (no rotation) and a label on each pin in nets."""
    pins_txt = "".join(f'\t\t(pin "{p}"\n\t\t\t(uuid "{U()}")\n\t\t)\n' for p in pinmap)
    out.append(f'\t(symbol\n\t\t(lib_id "{lib_id}")\n\t\t(at {x:g} {y:g} 0)\n\t\t(unit 1)\n'
               f'\t\t(exclude_from_sim no)\n\t\t(in_bom yes)\n\t\t(on_board yes)\n\t\t(dnp no)\n'
               f'\t\t(uuid "{U()}")\n'
               + prop("Reference", ref, x + 2.54, y - 1.27) + prop("Value", value, x + 2.54, y + 1.27)
               + prop("Footprint", footprint, x, y, True) + prop("Datasheet", "~", x, y, True)
               + prop("Description", "", x, y, True) + pins_txt
               + f'\t\t(instances\n\t\t\t(project ""\n\t\t\t\t(path "/{ROOT}"\n'
                 f'\t\t\t\t\t(reference "{ref}")\n\t\t\t\t\t(unit 1)\n\t\t\t\t)\n\t\t\t)\n\t\t)\n\t)\n')
    done = set()
    for num, net in nets.items():
        px, py, ang, _ = pinmap[num]
        spot = (round(x + px, 2), round(y - py, 2))
        if spot in done:           # stacked pins (the module's GNDs)
            continue
        done.add(spot)
        out.append(label(net, x + px, y - py, {180: 0, 0: 180, 270: 90, 90: 270}[ang]))


def wroom_gpio(name):
    if name.startswith("IO"):
        return int(name[2:])
    return {"RXD0": 44, "TXD0": 43, "USB_D-": 19, "USB_D+": 20}.get(name)


BOARD_5V = "+5V"
# Every R and C: 0805 with KiCad's hand-solder pads (longer, for an iron),
# the bulk caps included (10u/22u come in 0805).
R_FP = "Resistor_SMD:R_0805_2012Metric_Pad1.20x1.40mm_HandSolder"
C_FP = "Capacitor_SMD:C_0805_2012Metric_Pad1.18x1.45mm_HandSolder"
CBIG_FP = C_FP
counters = {"C": 1, "R": 8}


def nextref(kind):
    r = f"{kind}{counters[kind]}"
    counters[kind] += 1
    return r


boards = [
    # ref, ldo ref, centre, 3V3 net, EN net, IO0 net (None: the GPIO's net)
    # The main EN keeps the DevKitC carrier's net (MAIN_EN: the Sidecar's
    # GPIO11 resets it for serial flashing).
    ("U1", "U3", centers["U1"], power_net["U1"]["3V3"], power_net["U1"].get("CHIP_PU", "EN"), None),
    ("U2", "U4", centers["U2"], power_net["U2"]["3V3"], "SC_EN", "SC_BOOT"),
]
for ref, ldo_ref, (cx, cy), v33, en, io0 in boards:
    nets = {}
    for num, (_, _, _, name) in wroom.items():
        g = wroom_gpio(name)
        if name == "GND":
            nets[num] = "GND"
        elif name == "3V3":
            nets[num] = v33
        elif name == "EN":
            nets[num] = en
        elif g is not None and g in gpio_net[ref]:
            nets[num] = gpio_net[ref][g]
        elif g == 0 and io0:
            nets[num] = io0
    if ref == "U2" and io0:
        assert 0 not in gpio_net["U2"], "Sidecar IO0 has a net already"
    if ref == "U2":
        assert 48 not in gpio_net["U2"], "Sidecar GPIO48 has a net already"
        nets[[n for n, p in wroom.items() if p[3] == "IO48"][0]] = "SC_LED"
        assert 14 not in gpio_net["U2"], "Sidecar GPIO14 has a net already"
        nets[[n for n, p in wroom.items() if p[3] == "IO14"][0]] = "SD_CD"
        nets[[n for n, p in wroom.items() if p[3] == "RXD0"][0]] = "SC_RXD"
        nets[[n for n, p in wroom.items() if p[3] == "TXD0"][0]] = "SC_TXD"
    place("RF_Module:ESP32-S3-WROOM-1", ref, "ESP32-S3-WROOM-1-N8R2", "RF_Module:ESP32-S3-WROOM-1",
          cx, cy, wroom, nets)
    io0_net = nets[[n for n, p in wroom.items() if p[3] == "IO0"][0]]

    # Regulator and capacitors, below the module. They run from the board's
    # own 5 V rail; J6 joins it to the Atari's (PBI) 5 V.
    vin = BOARD_5V
    lx, ly = cx - 12.7, cy + 48.26
    place("Regulator_Linear:AMS1117-3.3", ldo_ref, "AMS1117-3.3",
          "Package_TO_SOT_SMD:SOT-223-3_TabPin2", lx, ly, ldo, {"3": vin, "1": "GND", "2": v33})
    for k, (net, val, fp) in enumerate([(vin, "10u", CBIG_FP), (v33, "22u", CBIG_FP),
                                        (v33, "100n", C_FP)]):
        x = lx + 17.78 + 7.62 * k
        place("Device:C", nextref("C"), val, fp, x, ly, cap, {"1": net, "2": "GND"})
    # Straps: EN RC reset, IO0 pull-up.
    sx, sy = cx + 22.86, cy + 48.26
    place("Device:R", nextref("R"), "10k", R_FP, sx, sy, res, {"1": v33, "2": en})
    place("Device:C", nextref("C"), "1u", C_FP, sx + 7.62, sy, cap, {"1": en, "2": "GND"})
    place("Device:R", nextref("R"), "10k", R_FP, sx + 15.24, sy, res, {"1": v33, "2": io0_net})

# J4: the Sidecar's debug/flash header (connect a USB-serial adapter's TX to RX).
c6pins = {str(i + 1): (-5.08, 5.08 - 2.54 * i, 0, f"Pin_{i + 1}") for i in range(6)}
place("Connector_Generic:Conn_01x06", "J4", "Sidecar debug: 5V GND BOOT EN RX TX",
      "Connector_PinHeader_2.54mm:PinHeader_1x06_P2.54mm_Vertical", 312.42, 50.8, c6pins,
      {"1": BOARD_5V, "2": "GND", "3": "SC_BOOT", "4": "SC_EN", "5": "SC_RXD", "6": "SC_TXD"})

# D1: the Sidecar's RGB status LED, as on the DevKitC-1 (v1.0): an
# SK6812MINI (WS2812 protocol) on GPIO48, from the Sidecar's 3V3.
place("LED:SK6812MINI", "D1", "SK6812MINI", "LED_SMD:LED_SK6812MINI_PLCC4_3.5x3.5mm_P1.75mm",
      297.18, 86.36, rgb, {"3": "SC_LED", "4": power_net["U2"]["3V3"], "2": "GND"})
place("Device:C", nextref("C"), "100n", C_FP, 312.42, 86.36, cap,
      {"1": power_net["U2"]["3V3"], "2": "GND"})
dx, dy, _, _ = rgb["1"]   # DOUT: no chained LEDs
out.append(f'\t(no_connect\n\t\t(at {297.18 + dx:g} {86.36 - dy:g})\n\t\t(uuid "{U()}")\n\t)\n')

# J2: the microSD socket (push-pull, Hirose DM3AT), on the Sidecar's 4-bit
# SDMMC pins, with R2-R6's pull-ups unchanged. Its card-detect switch runs
# from GND (DET_B) to SD_CD (DET_A), pulled up by R14, read on Sidecar IO14:
# a main-app input too, so a wrong image can't fight the switch (IO38, the
# other free pin, is the main app's D0, an output).
SDX, SDY = 345.44, 106.68
sd_nets = {"1": "SD_DAT2", "2": "SD_DAT3", "3": "SD_CMD", "4": power_net["U2"]["3V3"],
           "5": "SD_CLK", "6": "GND", "7": "SD_DAT0", "8": "SD_DAT1", "11": "GND",
           "9": "GND", "10": "SD_CD"}
place("Connector:Micro_SD_Card_Det_Hirose_DM3AT", "J2", "microSD (Hirose DM3AT-SF-PEJM5)",
      "Connector_Card:microSD_HC_Hirose_DM3AT-SF-PEJM5", SDX, SDY, sdsock, sd_nets)
place("Device:R", "R14", "10k", R_FP, 335.28, 127.0, res,
      {"1": power_net["U2"]["3V3"], "2": "SD_CD"})
place("Device:C", nextref("C"), "100n", C_FP, 325.12, 127.0, cap,
      {"1": power_net["U2"]["3V3"], "2": "GND"})

# J5: the main module's debug/flash header, J4's pinout. Its RX and TX are
# the main module's UART0 pins, which are also Atari D6 and D5: use it with
# the Atari off (J6 open), as ROM download mode needs anyway (IO46 = MPD).
main_nets = {}
for num, (_, _, _, name) in wroom.items():
    g = wroom_gpio(name)
    if g is not None and g in gpio_net["U1"]:
        main_nets[g] = gpio_net["U1"][g]
place("Connector_Generic:Conn_01x06", "J5", "Main debug: 5V GND BOOT EN RX TX (Atari off)",
      "Connector_PinHeader_2.54mm:PinHeader_1x06_P2.54mm_Vertical", 127.0, 50.8, c6pins,
      {"1": BOARD_5V, "2": "GND", "3": main_nets[0], "4": power_net["U1"].get("CHIP_PU", "EN"),
       "5": main_nets[44], "6": main_nets[43]})

# J6: the PBI's 5 V (VCC50_1, J1.47) to the board's rail (+5V). Jumper on:
# the Atari powers both modules. Off: they run from J4/J5's 5 V, and nothing
# back-feeds the Atari.
c2pins = {"1": (-5.08, 0, 0, "Pin_1"), "2": (-5.08, -2.54, 0, "Pin_2")}
place("Connector_Generic:Conn_01x02", "J6", "5V: on = Atari powers the board",
      "Connector_PinHeader_2.54mm:PinHeader_1x02_P2.54mm_Vertical", 127.0, 160.02, c2pins,
      {"1": power_net["U1"]["5V"], "2": BOARD_5V})

NOTE = ("sidecar_smd (speculative): espBusBangSidecar with bare ESP32-S3-WROOM-1-N8R2 modules for U1 "
        "(main) and U2 (Sidecar), same nets per GPIO. Each: AMS1117-3.3 from the board rail (+5V, J6 to the PBI 5V), "
        "10u in, 22u out, 100n at the module, EN 10k/1u RC reset, IO0 10k pull-up (boot from flash).\\n"
        "J4 Sidecar debug/flash: 1 +5V, 2 GND, 3 BOOT (IO0, low = download), 4 EN, 5 RX (RXD0/GPIO44), "
        "6 TX (TXD0/GPIO43). J5, main debug/flash: same pinout on the main module; its RX/TX are Atari D6/D5, "
        "so use it with the Atari off.\\n"
        "J6: PBI 5V (VCC50_1) to the board rail (+5V): fit to run from the Atari; remove when powering "
        "from J4/J5, so the Atari isn't back-fed.\\n"
        "D1: the Sidecar's RGB status LED (SK6812MINI on GPIO48, as on the DevKitC-1). "
        "J2: microSD socket (Hirose DM3AT) replacing the breakout header, same SD_* nets; card detect SD_CD on IO14, "
        "pulled up by R14. All R and C: 0805 hand-solder footprints.")
out.append(f'\t(text "{NOTE}"\n\t\t(exclude_from_sim no)\n\t\t(at 210.82 190.5 0)\n\t\t(effects\n'
           f'\t\t\t(font\n\t\t\t\t(size 1.27 1.27)\n\t\t\t)\n\t\t\t(justify left bottom)\n\t\t)\n'
           f'\t\t(uuid "{U()}")\n\t)\n')

# The parts inherited from the DevKitC carrier (R1-R7, R12, R13) get the
# same hand-solder 0805 footprints.
def smd_fp(m):
    blk = m.group(0)
    fp = R_FP if '(lib_id "Device:R")' in blk else C_FP
    return re.sub(r'\(property "Footprint" "[^"]*"', f'(property "Footprint" "{fp}"', blk, count=1)


s = re.sub(r'\n\t\(symbol\n\t\t\(lib_id "Device:[RC]"\).*?\n\t\)', smd_fp, s, flags=re.S)
out = [re.sub(r'\(property "Footprint" "Resistor_THT:[^"]*"', f'(property "Footprint" "{R_FP}"', t)
       for t in out]

k = s.index('\t(sheet_instances')
s = s[:k] + "".join(out) + s[k:]
open(dst, "w").write(s)
print("U1 GPIO nets", len(gpio_net["U1"]), "U2 GPIO nets", len(gpio_net["U2"]))
